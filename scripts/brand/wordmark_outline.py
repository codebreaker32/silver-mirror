#!/usr/bin/env python3
"""Outline the "Silver Mirror" wordmark from Noto Serif Display into SVG paths.

Run on the build VM (needs fontTools; see scripts/brand/README.md):
    PYTHONPATH=/tmp/ftlib/lib python3 scripts/brand/wordmark_outline.py

Writes:
    apps/mobile/src/brand/wordmarkPaths.ts   (consumed by Wordmark.tsx)
    design/brand/wordmark.svg                (reference / web)

Shaping: advance widths plus the font's own GPOS pair kerning (PairPos formats 1 and 2), plus a
small positive tracking that suits a high-contrast display face set as a logo. No ligatures needed.
The outlines are glyph paths, so the wordmark renders identically with or without the font loaded.
"""
import glob
import os
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
TEXT = "Silver Mirror"
WEIGHT = "400Regular"
TRACKING_EM = 0.018  # +18/1000 em


def find_font():
    pats = glob.glob(os.path.join(ROOT, "node_modules", "@expo-google-fonts", "noto-serif-display", "**", f"NotoSerifDisplay_{WEIGHT}.ttf"), recursive=True)
    if not pats:
        sys.exit("NotoSerifDisplay ttf not found: run npm install first")
    return pats[0]


def pair_kerning(font):
    """Return {(left, right): xAdvance} from GPOS 'kern' PairPos lookups."""
    kern = {}
    if "GPOS" not in font:
        return kern
    gpos = font["GPOS"].table
    idx = set()
    for fr in gpos.FeatureList.FeatureRecord:
        if fr.FeatureTag == "kern":
            idx.update(fr.Feature.LookupListIndex)
    for i in sorted(idx):
        lookup = gpos.LookupList.Lookup[i]
        for st in lookup.SubTable:
            kind = lookup.LookupType
            if kind == 9:
                kind = st.ExtensionLookupType
                st = st.ExtSubTable
            if kind != 2:
                continue
            cov = st.Coverage.glyphs
            if st.Format == 1:
                for gi, first in enumerate(cov):
                    for pvr in st.PairSet[gi].PairValueRecord:
                        v = pvr.Value1
                        adv = getattr(v, "XAdvance", 0) if v else 0
                        if adv and (first, pvr.SecondGlyph) not in kern:
                            kern[(first, pvr.SecondGlyph)] = adv
            elif st.Format == 2:
                cd1 = st.ClassDef1.classDefs
                cd2 = st.ClassDef2.classDefs
                for first in cov:
                    c1 = cd1.get(first, 0)
                    row = st.Class1Record[c1]
                    for second, c2 in cd2.items():
                        v = row.Class2Record[c2].Value1
                        adv = getattr(v, "XAdvance", 0) if v else 0
                        if adv and (first, second) not in kern:
                            kern[(first, second)] = adv
    return kern


def main():
    path = find_font()
    font = TTFont(path)
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    kern = pair_kerning(font)
    track = round(TRACKING_EM * upm)

    names = [cmap[ord(c)] for c in TEXT]
    x = 0
    glyph_paths = []
    bounds = BoundsPen(gs)
    for i, gn in enumerate(names):
        pen = SVGPathPen(gs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
        # Flip y (font units are y-up) and place at x.
        gs[gn].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
        gs[gn].draw(TransformPen(bounds, (1, 0, 0, -1, x, 0)))
        d = pen.getCommands()
        if d:
            glyph_paths.append(d)
        adv = hmtx[gn][0]
        if i + 1 < len(names):
            adv += kern.get((gn, names[i + 1]), 0) + (track if TEXT[i] != " " else 0)
        x += adv

    xmin, ymin, xmax, ymax = bounds.bounds
    pad = round(0.01 * upm)
    vb = (round(xmin) - pad, round(ymin) - pad, round(xmax - xmin) + 2 * pad, round(ymax - ymin) + 2 * pad)
    # Cap height in the same units, so callers can size the wordmark by cap height.
    cap = getattr(font["OS/2"], "sCapHeight", 0) or round(-ymin)

    d_all = " ".join(glyph_paths)
    ts = f"""// GENERATED by scripts/brand/wordmark_outline.py from {os.path.basename(path)} (Noto Serif Display, OFL).
// Do not edit by hand. "{TEXT}" outlined with the font GPOS kerning and +{TRACKING_EM}em tracking.
export const WORDMARK = {{
  text: {TEXT!r},
  viewBox: [{vb[0]}, {vb[1]}, {vb[2]}, {vb[3]}] as const,
  unitsPerEm: {upm},
  capHeight: {cap},
  d: {d_all!r},
}} as const;
"""
    out_ts = os.path.join(ROOT, "apps", "mobile", "src", "brand", "wordmarkPaths.ts")
    with open(out_ts, "w") as f:
        f.write(ts.replace("'", '"'))
    os.makedirs(os.path.join(ROOT, "design", "brand"), exist_ok=True)
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb[0]} {vb[1]} {vb[2]} {vb[3]}" role="img" aria-label="{TEXT}"><path fill="currentColor" d="{d_all}"/></svg>\n'
    with open(os.path.join(ROOT, "design", "brand", "wordmark.svg"), "w") as f:
        f.write(svg)
    print(f"wordmark: {len(names)} glyphs, {len(kern)} kern pairs, viewBox {vb}, cap {cap}, {len(d_all)} chars")


if __name__ == "__main__":
    main()
