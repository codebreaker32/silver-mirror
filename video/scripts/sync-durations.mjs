// Turns public/voiceover/durations.json (+ <scene>.marks.json, voice and clip files)
// into src/durations.ts so the composition knows, at bundle time, how long each
// scene is and which media exist. Safe to run when nothing has been generated yet.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pub = path.join(root, "public");
const SCENES = ["hook", "shelf", "gap", "scan", "share", "verdict", "tryon", "tour", "proof", "close"];
const FALLBACK = [6, 7, 6, 16, 7, 13, 8, 11, 8, 7];
const TAIL = 0.6;
const LEAD = 0.3; // voice starts 0.3s into each scene

const readJson = (p) => {
  try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; }
};

const raw = readJson(path.join(pub, "voiceover", "durations.json")) ?? {};
const secondsOf = (v) => {
  if (typeof v === "number") return v;
  if (v && typeof v === "object") {
    for (const k of ["seconds", "duration", "durationSeconds", "secs", "s"]) if (typeof v[k] === "number") return v[k];
    if (typeof v.ms === "number") return v.ms / 1000;
    if (typeof v.durationMs === "number") return v.durationMs / 1000;
  }
  return null;
};
const lookup = (id) => {
  if (Array.isArray(raw)) {
    const hit = raw.find((r) => r && (r.id === id || r.scene === id || r.name === id));
    return hit ? secondsOf(hit) : null;
  }
  return secondsOf(raw[id] ?? (raw.scenes ? raw.scenes[id] : undefined));
};

// Speech marks: JSON array, {marks:[...]}, or Polly-style JSON lines. Times in ms.
const readMarks = (id) => {
  const p = path.join(pub, "voiceover", `${id}.marks.json`);
  if (!fs.existsSync(p)) return null;
  const text = fs.readFileSync(p, "utf8").trim();
  let arr = null;
  try {
    const j = JSON.parse(text);
    arr = Array.isArray(j) ? j : j.marks ?? j.words ?? null;
  } catch {
    arr = text.split(/\r?\n/).filter(Boolean).map((l) => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean);
  }
  if (!Array.isArray(arr)) return null;
  const out = [];
  for (const m of arr) {
    if (!m) continue;
    if (m.type && m.type !== "word") continue;
    const w = m.value ?? m.word ?? m.text;
    let t = m.time ?? m.start ?? m.startMs ?? m.offset ?? m.t;
    if (typeof m.start_time === "number") t = m.start_time * 1000;
    if (typeof w !== "string" || typeof t !== "number") continue;
    if (w.startsWith("<")) continue; // SSML tags such as <break/> come back as "words"
    out.push({ w, t: Math.round(t) });
  }
  return out.length ? out : null;
};

const findFile = (dir, id, exts) => {
  for (const e of exts) {
    const rel = `${dir}/${id}.${e}`;
    if (fs.existsSync(path.join(pub, rel)) && fs.statSync(path.join(pub, rel)).size > 0) return rel;
  }
  return null;
};

const scenes = SCENES.map((id, i) => {
  const voice = lookup(id);
  const voiceFile = findFile("voiceover", id, ["mp3", "wav", "m4a"]);
  const seconds = voice && voice > 0 ? LEAD + voice + TAIL : FALLBACK[i];
  return {
    id,
    seconds: Math.round(seconds * 100) / 100,
    voiceSeconds: voice && voice > 0 ? voice : null,
    voice: voiceFile,
    clip: findFile("clips", id, ["mp4"]),
    marks: readMarks(id),
  };
});

const src = `// GENERATED by scripts/sync-durations.mjs. Do not edit by hand.
export type Mark = { w: string; t: number };
export type SceneMeta = {
  id: string;
  seconds: number;
  voiceSeconds: number | null;
  voice: string | null;
  clip: string | null;
  marks: Mark[] | null;
};
export const SCENE_META: SceneMeta[] = ${JSON.stringify(scenes, null, 2)};
`;
fs.writeFileSync(path.join(root, "src", "durations.ts"), src);
const total = scenes.reduce((a, s) => a + s.seconds, 0);
for (const s of scenes) {
  console.log(`${s.id.padEnd(8)} ${s.seconds.toFixed(2)}s voice=${s.voice ?? "-"} clip=${s.clip ?? "-"} marks=${s.marks ? s.marks.length : 0}`);
}
console.log(`total ${total.toFixed(2)}s`);
