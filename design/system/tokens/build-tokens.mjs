// Generates theme.ts (React Native / Expo) and tokens.css (web) from
// skinkey.tokens.json. Node 18+, no dependencies.
//   node build-tokens.mjs
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTokens, resolve, isAlias, lookup, MODES } from './lib/resolve.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = loadTokens(join(here, 'skinkey.tokens.json'));
const BANNER = `GENERATED by build-tokens.mjs from skinkey.tokens.json v${tokens.$meta.version}. Do not edit by hand.`;

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/\./g, '-').toLowerCase();
const strip = (o) => {
  if (Array.isArray(o)) return o.map(strip);
  if (o && typeof o === 'object') return Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [k, strip(v)]));
  return o;
};
const camelKeys = (o) => {
  if (Array.isArray(o)) return o.map(camelKeys);
  if (o && typeof o === 'object') return Object.fromEntries(Object.entries(o).map(([k, v]) => [camel(k), camelKeys(v)]));
  return o;
};

// ------------------------------------------------------------ RN typography
const FONT = tokens.typography.expoFonts;
function rnType(style) {
  const t = {
    fontFamily: FONT[style.font],
    fontSize: style.size,
    lineHeight: style.lineHeight,
    letterSpacing: style.letterSpacing,
    includeFontPadding: false,
  };
  if (style.transform === 'uppercase') t.textTransform = 'uppercase';
  if (style.numeric === 'tabular') t.fontVariant = ['tabular-nums'];
  return t;
}
const typographyRN = Object.fromEntries(Object.entries(tokens.typography.scale).map(([k, v]) => [k, rnType(v)]));
const MAX_SCALE = tokens.typography.rules.maxFontSizeMultiplier;
const textPropsRN = Object.fromEntries(Object.keys(tokens.typography.scale).map((k) => [k, { allowFontScaling: true, maxFontSizeMultiplier: MAX_SCALE }]));

// Resolve a component/elevation subtree for RN: type refs become RN text styles.
function resolveRN(value, mode) {
  if (isAlias(value)) {
    const hit = lookup(tokens, value, mode);
    if (hit.kind === 'type') return typographyRN[hit.name];
    if (hit.kind === 'ease') return hit.value.bezier;
    if (hit.kind === 'elevation' && /^\{elevation\.\d\}$/.test(value)) return rnElevation(mode)[value.slice(11, -1)].style;
    return resolveRN(hit.value, mode);
  }
  if (Array.isArray(value)) return value.map((v) => resolveRN(v, mode));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [camel(k), resolveRN(v, mode)]));
  }
  return value;
}

function rnElevation(mode) {
  const out = {};
  for (const [lvl, e] of Object.entries(strip(tokens.elevation[mode]))) {
    const surface = resolve(tokens, e.surface, mode);
    const border = e.border === 'none' ? null : resolve(tokens, e.border, mode);
    const style = { backgroundColor: surface, borderWidth: border ? 1 : 0, borderColor: border ?? 'transparent', elevation: e.rn.elevation };
    // Explicit zero shadows where a level has none, so light and dark share one shape.
    Object.assign(style, e.rn.shadowColor
      ? { shadowColor: resolve(tokens, e.rn.shadowColor, mode), shadowOpacity: e.rn.shadowOpacity, shadowRadius: e.rn.shadowRadius, shadowOffset: { width: 0, height: e.rn.shadowOffsetY } }
      : { shadowColor: 'transparent', shadowOpacity: 0, shadowRadius: 0, shadowOffset: { width: 0, height: 0 } });
    out[lvl] = { surface, border: border ?? 'transparent', boxShadow: e.shadow, style };
  }
  return out;
}

function themeFor(mode) {
  return {
    scheme: mode,
    dark: mode === 'dark',
    colors: camelKeys(resolve(tokens, tokens.semantic.color[mode], mode)),
    elevation: rnElevation(mode),
    grain: { opacity: tokens.texture.grain[mode].opacity },
    components: resolveRN(tokens.component, mode),
  };
}

// Infer a TS type literal from a value (both modes must share it).
function tsType(v, indent = '  ') {
  if (Array.isArray(v)) {
    const inner = v.length ? [...new Set(v.map((x) => tsType(x, indent)))].join(' | ') : 'never';
    return `readonly (${inner})[]`;
  }
  if (v === null) return 'null';
  if (typeof v === 'object') {
    const pad = indent + '  ';
    const body = Object.entries(v).map(([k, x]) => `${pad}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${tsType(x, pad)};`).join('\n');
    return `{\n${body}\n${indent}}`;
  }
  return typeof v;
}
function shape(v) {
  if (Array.isArray(v)) return 'array';
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, shape(x)]));
  return typeof v;
}

const light = themeFor('light');
const dark = themeFor('dark');
for (const key of ['colors', 'elevation', 'components', 'grain']) {
  if (JSON.stringify(shape(light[key])) !== JSON.stringify(shape(dark[key]))) {
    throw new Error(`Light and dark themes differ in shape at "${key}". Every token must exist in both modes.`);
  }
}

