#!/usr/bin/env node
// Generates theme.ts (React Native / Expo) and tokens.css (web) from
// skinkey.tokens.json. Node 18+, no dependencies.
//   node build-tokens.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTokens, resolve, isAlias, lookup, MODES } from './lib/resolve.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = loadTokens(join(here, 'skinkey.tokens.json'));
const BANNER = `GENERATED by build-tokens.mjs from skinkey.tokens.json v${tokens.$meta.version}. Do not edit by hand.`;

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/\./g, '-').toLowerCase();
const strip = (o) => {
  if (Array.isArray(o)) return o.map(strip);
  if (o && typeof o === 'object') return Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [k, strip(v)]));
  return o;
};
const camelKeys = (o) => {
  if (Array.isArray(o)) return o.map(camelKeys);
  if (o && typeof o === 'object') return Object.fromEntries(Object.entries(o).map(([k, v]) => [camel(k), camelKeys(v)]));
  return o;
};

// ------------------------------------------------------------ RN typography
const FONT = tokens.typography.expoFonts;
function rnType(style) {
  const t = {
    fontFamily: FONT[style.font],
    fontSize: style.size,
    lineHeight: style.lineHeight,
    letterSpacing: style.letterSpacing,
    includeFontPadding: false,
  };
  if (style.transform === 'uppercase') t.textTransform = 'uppercase';
  if (style.numeric === 'tabular') t.fontVariant = ['tabular-nums'];
  return t;
}
const typographyRN = Object.fromEntries(Object.entries(tokens.typography.scale).map(([k, v]) => [k, rnType(v)]));

// Resolve a component/elevation subtree for RN: type refs become RN text styles.
function resolveRN(value, mode) {
  if (isAlias(value)) {
    const hit = lookup(tokens, value, mode);
    if (hit.kind === 'type') return typographyRN[hit.name];
    if (hit.kind === 'ease') return hit.value.bezier;
    return resolveRN(hit.value, mode);
  }
  if (Array.isArray(value)) return value.map((v) => resolveRN(v, mode));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [camel(k), resolveRN(v, mode)]));
  }
  return value;
}

function rnElevation(mode) {
  const out = {};
  for (const [lvl, e] of Object.entries(strip(tokens.elevation[mode]))) {
    const surface = resolve(tokens, e.surface, mode);
    const border = e.border === 'none' ? null : resolve(tokens, e.border, mode);
    const style = { backgroundColor: surface, borderWidth: border ? 1 : 0, borderColor: border ?? 'transparent', elevation: e.rn.elevation };
    // Explicit zero shadows where a level has none, so light and dark share one shape.
    Object.assign(style, e.rn.shadowColor
      ? { shadowColor: e.rn.shadowColor, shadowOpacity: e.rn.shadowOpacity, shadowRadius: e.rn.shadowRadius, shadowOffset: { width: 0, height: e.rn.shadowOffsetY } }
      : { shadowColor: 'transparent', shadowOpacity: 0, shadowRadius: 0, shadowOffset: { width: 0, height: 0 } });
    out[lvl] = { surface, border: border ?? 'transparent', boxShadow: e.shadow, style };
  }
  return out;
}

function themeFor(mode) {
  return {
    scheme: mode,
    dark: mode === 'dark',
    colors: camelKeys(resolve(tokens, tokens.semantic.color[mode], mode)),
    elevation: rnElevation(mode),
    grain: { opacity: tokens.texture.grain[mode].opacity },
    components: resolveRN(tokens.component, mode),
  };
}

// Infer a TS type literal from a value (both modes must share it).
function tsType(v, indent = '  ') {
  if (Array.isArray(v)) {
    const inner = v.length ? [...new Set(v.map((x) => tsType(x, indent)))].join(' | ') : 'never';
    return `readonly (${inner})[]`;
  }
  if (v === null) return 'null';
  if (typeof v === 'object') {
    const pad = indent + '  ';
    const body = Object.entries(v).map(([k, x]) => `${pad}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${tsType(x, pad)};`).join('\n');
    return `{\n${body}\n${indent}}`;
  }
  return typeof v;
}
function shape(v) {
  if (Array.isArray(v)) return 'array';
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, shape(x)]));
  return typeof v;
}

const light = themeFor('light');
const dark = themeFor('dark');
for (const key of ['colors', 'elevation', 'components', 'grain']) {
  if (JSON.stringify(shape(light[key])) !== JSON.stringify(shape(dark[key]))) {
    throw new Error(`Light and dark themes differ in shape at "${key}". Every token must exist in both modes.`);
  }
}

const lit = (o) => JSON.stringify(o, null, 2);
const fontKeys = Object.entries(FONT).filter(([k]) => !k.startsWith('$'));
const serifKeys = fontKeys.filter(([k]) => k.startsWith('serif')).map(([, v]) => v);
const sansKeys = fontKeys.filter(([k]) => k.startsWith('sans')).map(([, v]) => v);

const motion = strip(tokens.motion);
const motionTS = {
  duration: motion.duration,
  ease: Object.fromEntries(Object.entries(motion.ease).map(([k, v]) => [k, v.bezier])),
  timing: motion.timing,
  reduced: { duration: motion.reducedMotion.duration, translate: motion.reducedMotion.translate, scaleFrom: motion.reducedMotion.scaleFrom, stagger: motion.reducedMotion.stagger },
};

const ts = `// ${BANNER}
// SkinKey design tokens for React Native (Expo). Direction: ${tokens.$meta.direction}.
//
// Usage:
//   const [loaded] = useFonts(fontAssets);            // from expo-font or either @expo-google-fonts package
//   const theme = useSkinKeyTheme();                   // follows the system light/dark setting
//   <Text style={[theme.type.reason, { color: theme.colors.text }]}>...</Text>
//   <Pressable style={{ minHeight: theme.touch.min }} />
//
// Notes:
// - Text styles carry no fontWeight: on Android a custom family must not be combined with
//   fontWeight, so the weight is baked into the family key (Newsreader_500Medium).
// - Elevation: use elevation[n].style (classic shadow props + Android elevation) OR, on the
//   new architecture, elevation[n].boxShadow with backgroundColor. Never both. Dark mode has no shadows.
// - Motion: pass motion.ease.* to Easing.bezier(...). When reduce motion is on, use motion.reduced.

import { useColorScheme } from 'react-native';
import type { TextStyle } from 'react-native';
import {
${serifKeys.map((k) => `  ${k},`).join('\n')}
} from '@expo-google-fonts/newsreader';
import {
${sansKeys.map((k) => `  ${k},`).join('\n')}
} from '@expo-google-fonts/commissioner';

/** Pass to useFonts(). Keys are the fontFamily names used in \`type\`. */
export const fontAssets = {
${[...serifKeys, ...sansKeys].map((k) => `  ${k},`).join('\n')}
} as const;

/** Font family keys by role. */
export const fonts = ${lit(Object.fromEntries(fontKeys.map(([k, v]) => [camel(k), v])))} as const;

/** Web font stacks, for react-native-web or shared code. */
export const webFontStacks = ${lit({ serif: tokens.typography.family.serif.web, sans: tokens.typography.family.sans.web })} as const;

export type FontFamilyKey = keyof typeof fontAssets;

/** Primitive palette. Components should use theme.colors, not these. */
export const palette = ${lit(strip(tokens.primitive.color))} as const;

export type TypeStyleName = ${Object.keys(typographyRN).map((k) => `'${k}'`).join(' | ')};
export interface TypeStyle extends TextStyle {
  fontFamily: FontFamilyKey;
  fontSize: number;
  lineHeight: number;
  letterSpacing: number;
}

/** Type scale (dp). Minimum size is ${tokens.typography.rules.minSize}. */
export const type: Record<TypeStyleName, TypeStyle> = ${lit(typographyRN)};

/** 4dp spacing scale plus semantic aliases. */
export const space = ${lit(tokens.spacing.scale)} as const;
export const spacing = ${lit(camelKeys(tokens.spacing.semantic))} as const;

export const radius = ${lit(strip(tokens.radius))} as const;

export const touch = ${lit(strip(tokens.touch))} as const;

export const icon = ${lit({ sm: tokens.icon.sm, md: tokens.icon.md, lg: tokens.icon.lg, xl: tokens.icon.xl, stroke: tokens.icon.stroke, verdictSize: tokens.icon.verdict.size, verdictGlyph: Object.fromEntries(['fits', 'caution', 'unknown', 'medicine'].map((v) => [v, tokens.icon.verdict[v].glyph])) })} as const;

export const zIndex = ${lit(strip(tokens.zIndex))} as const;

/** Durations in ms; easing as cubic-bezier control points. No springs, no overshoot. */
export const motion = ${lit(motionTS)} as const;

export type ColorScheme = 'light' | 'dark';
export type Verdict = 'fits' | 'caution' | 'unknown' | 'medicine';

export interface ThemeColors ${tsType(light.colors, '')}

export interface ElevationLevel {
  surface: string;
  border: string;
  /** CSS box-shadow string, for RN new-architecture boxShadow. 'none' in dark mode. */
  boxShadow: string;
  /** Classic shadow props + Android elevation, ready to spread into a View style. */
  style: {
    backgroundColor: string;
    borderWidth: number;
    borderColor: string;
    elevation: number;
    shadowColor: string;
    shadowOpacity: number;
    shadowRadius: number;
    shadowOffset: { width: number; height: number };
  };
}

export interface ThemeComponents ${tsType(light.components, '')}

export interface SkinKeyTheme {
  scheme: ColorScheme;
  dark: boolean;
  colors: ThemeColors;
  elevation: Record<'0' | '1' | '2' | '3', ElevationLevel>;
  /** Paper grain: static tile only, never behind body text. Always 0 in dark mode. */
  grain: { opacity: number };
  components: ThemeComponents;
  type: typeof type;
  space: typeof space;
  spacing: typeof spacing;
  radius: typeof radius;
  touch: typeof touch;
  icon: typeof icon;
  zIndex: typeof zIndex;
  motion: typeof motion;
  fonts: typeof fonts;
}

const shared = { type, space, spacing, radius, touch, icon, zIndex, motion, fonts };

export const lightTheme: SkinKeyTheme = {
  ...${lit(light).replace(/\n/g, '\n  ')},
  ...shared,
};

export const darkTheme: SkinKeyTheme = {
  ...${lit(dark).replace(/\n/g, '\n  ')},
  ...shared,
};

export const themes: Record<ColorScheme, SkinKeyTheme> = { light: lightTheme, dark: darkTheme };

export function getTheme(scheme: ColorScheme | null | undefined): SkinKeyTheme {
  return scheme === 'dark' ? darkTheme : lightTheme;
}

/** Follows the system setting; pass an override from user settings if the app has one. */
export function useSkinKeyTheme(override?: ColorScheme): SkinKeyTheme {
  const system = useColorScheme();
  return getTheme(override ?? system);
}

/** Verdict head colours for a verdict, e.g. theme.colors.verdict[v]. */
export function verdictColors(theme: SkinKeyTheme, v: Verdict) {
  return theme.colors.verdict[v];
}
`;
writeFileSync(join(here, 'theme.ts'), ts);

// ====================================================================== CSS
const P = '--sk';
const lines = [];
const decl = (name, value, indent = '  ') => lines.push(`${indent}${P}-${name}: ${value};`);
const primName = (ref) => ref.slice(1, -1).replace(/\./g, '-');

function cssColorRef(ref, mode) {
  // Semantic colour value -> var(--sk-<primitive>) when it aliases a primitive.
  if (isAlias(ref)) {
    const hit = lookup(tokens, ref, mode);
    if (hit.kind === 'primitive') return `var(${P}-${primName(ref)})`;
  }
  return ref;
}

function cssRef(value, key) {
  // Component-layer value -> CSS value (var() reference or literal with unit).
  if (isAlias(value)) {
    const [head, ...rest] = value.slice(1, -1).split('.');
    const path = rest.join('-');
    switch (head) {
      case 'color': return `var(${P}-color-${kebab(path)})`;
      case 'verdict': return `var(${P}-verdict-${kebab(path)})`;
      case 'meter': return `var(${P}-meter-${kebab(path)})`;
      case 'space': return `var(${P}-space-${kebab(path)})`;
      case 'radius': return `var(${P}-radius-${path})`;
      case 'type': return `var(${P}-type-${kebab(path)})`;
      case 'elevation': return `var(${P}-elevation-${path})`;
      case 'icon': return `var(${P}-icon-${kebab(path)})`;
      case 'touch': return `var(${P}-touch-${kebab(path)})`;
      case 'z': return `var(${P}-z-${kebab(path)})`;
      case 'duration': return `var(${P}-duration-${kebab(path)})`;
      default: return `var(${P}-${primName(value)})`;
    }
  }
  if (typeof value === 'number') {
    if (/Pct$/.test(key)) return `${value}%`;
    if (/(aspect|opacity|items|segments|elevation|stackAtFontScale)$/i.test(key)) return String(value);
    return `${value}px`;
  }
  if (typeof value === 'string' && /^(#|rgba?\(|transparent$|none$|dashed$|solid$|start$|horizontal$)/.test(value)) return value;
  return null; // prose, component references, icon names: not CSS values
}

function emitComponents(obj, prefix) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$') || Array.isArray(v) || typeof v === 'boolean') continue;
    const name = prefix ? `${prefix}-${kebab(k)}` : kebab(k);
    if (v && typeof v === 'object') { emitComponents(v, name); continue; }
    const css = cssRef(v, k);
    if (css !== null) decl(name, css);
  }
}

function emitSemantic(mode) {
  const sem = strip(tokens.semantic.color[mode]);
  for (const [k, v] of Object.entries(sem)) {
    if (k === 'verdict') {
      for (const [vk, vv] of Object.entries(v)) for (const [p, c] of Object.entries(vv)) decl(`verdict-${vk}-${p}`, cssColorRef(c, mode));
    } else if (k === 'meter') {
      for (const [p, c] of Object.entries(v)) decl(`meter-${p}`, cssColorRef(c, mode));
    } else if (typeof v === 'object') {
      for (const [p, c] of Object.entries(v)) decl(`color-${k}-${p}`, cssColorRef(c, mode));
    } else {
      decl(`color-${k}`, cssColorRef(v, mode));
    }
  }
  for (const [lvl, e] of Object.entries(strip(tokens.elevation[mode]))) {
    decl(`elevation-${lvl}-surface`, cssRef(e.surface));
    decl(`elevation-${lvl}-border`, e.border === 'none' ? 'transparent' : cssRef(e.border));
    decl(`elevation-${lvl}-shadow`, e.shadow);
  }
  decl('grain-opacity', String(tokens.texture.grain[mode].opacity));
}

lines.push(`/* ${BANNER}`);
lines.push(` * SkinKey web tokens (results / fallback page and landing). Direction: ${tokens.$meta.direction}.`);
lines.push(' * Theme: follows prefers-color-scheme; force with <html data-theme="light|dark">.');
lines.push(' * Semantic and component tokens are re-declared on every [data-theme] element so a themed');
lines.push(' * subtree (for example a dark preview frame) resolves its own values. 1dp = 1px. */');
lines.push('');
lines.push('/* ===== Layer 1: primitives ===== */');
lines.push(':root {');
for (const [ramp, steps] of Object.entries(strip(tokens.primitive.color))) {
  if (typeof steps === 'string') { decl(ramp, steps); continue; }
  for (const [s, hexv] of Object.entries(steps)) decl(`${ramp}-${s}`, hexv);
}
lines.push('');
lines.push('  /* Type families and scale. Font shorthand: font: var(--sk-type-body); then apply the');
lines.push('     matching letter-spacing, or use the .sk-type-* classes below. */');
decl('font-serif', tokens.typography.family.serif.web);
decl('font-sans', tokens.typography.family.sans.web);
for (const [k, s] of Object.entries(tokens.typography.scale)) {
  const n = kebab(k);
  const fam = `var(${P}-font-${s.family})`;
  decl(`type-${n}`, `${s.italic ? 'italic ' : ''}${s.weight} ${s.size}px/${s.lineHeight}px ${fam}`);
  decl(`type-${n}-size`, `${s.size}px`);
  decl(`type-${n}-line`, `${s.lineHeight}px`);
  decl(`type-${n}-weight`, String(s.weight));
  decl(`type-${n}-tracking`, `${+(s.letterSpacing / s.size).toFixed(4)}em`);
}
lines.push('');
lines.push('  /* Spacing (4dp base), radius, touch, icons, z-index */');
for (const [k, v] of Object.entries(tokens.spacing.scale)) decl(`space-${k}`, `${v}px`);
for (const [k, v] of Object.entries(tokens.spacing.semantic)) decl(`space-${kebab(k)}`, `${v}px`);
for (const [k, v] of Object.entries(strip(tokens.radius))) decl(`radius-${k}`, `${v}px`);
for (const [k, v] of Object.entries(strip(tokens.touch))) decl(`touch-${kebab(k)}`, `${v}px`);
for (const k of ['sm', 'md', 'lg', 'xl']) decl(`icon-${k}`, `${tokens.icon[k]}px`);
decl('icon-verdict-size', `${tokens.icon.verdict.size}px`);
decl('icon-stroke', String(tokens.icon.stroke));
for (const [k, v] of Object.entries(strip(tokens.zIndex))) decl(`z-${kebab(k)}`, String(v));
decl('focus-ring-width', `${tokens.component.button.focusRing.width}px`);
decl('focus-ring-offset', `${tokens.component.button.focusRing.offset}px`);
lines.push('');
lines.push('  /* Motion: ink settling. No springs, no overshoot, nothing loops. */');
for (const [k, v] of Object.entries(motion.duration)) decl(`duration-${kebab(k)}`, `${v}ms`);
for (const [k, v] of Object.entries(motion.ease)) decl(`ease-${kebab(k)}`, `cubic-bezier(${v.bezier.join(', ')})`);
decl('motion-translate', '6px');
decl('motion-scale-from', '0.98');
lines.push('  --sk-grain-tile: url("/assets/texture/grain-160.png");');
lines.push('}');
lines.push('');
lines.push('/* ===== Layer 2: semantic, light (default) ===== */');
lines.push(':root,');
lines.push('[data-theme="light"] {');
lines.push('  color-scheme: light;');
emitSemantic('light');
lines.push('}');
lines.push('');
lines.push('/* ===== Layer 2: semantic, dark ===== */');
lines.push('[data-theme="dark"] {');
lines.push('  color-scheme: dark;');
emitSemantic('dark');
lines.push('}');
lines.push('');
lines.push('@media (prefers-color-scheme: dark) {');
lines.push('  :root:not([data-theme="light"]) {');
lines.push('    color-scheme: dark;');
const before = lines.length;
emitSemantic('dark');
for (let i = before; i < lines.length; i++) lines[i] = '  ' + lines[i];
lines.push('  }');
lines.push('}');
lines.push('');
lines.push('/* ===== Layer 3: components (reference semantic tokens only) ===== */');
lines.push(':root,');
lines.push('[data-theme] {');
emitComponents(strip(tokens.component), '');
lines.push('}');
lines.push('');
lines.push('/* ===== Reduced motion: every transition becomes a 120ms crossfade ===== */');
lines.push('@media (prefers-reduced-motion: reduce) {');
lines.push('  :root {');
for (const k of Object.keys(motion.duration)) {
  const v = k === 'instant' || k === 'reasonStagger' ? 0 : motion.reducedMotion.duration;
  lines.push(`    ${P}-duration-${kebab(k)}: ${v}ms;`);
}
lines.push(`    ${P}-motion-translate: 0px;`);
lines.push(`    ${P}-motion-scale-from: 1;`);
lines.push('  }');
lines.push('}');
lines.push('');
lines.push('/* ===== Utilities ===== */');
for (const [k, s] of Object.entries(tokens.typography.scale)) {
  const n = kebab(k);
  const extra = [s.transform ? `text-transform: ${s.transform};` : '', s.numeric === 'tabular' ? 'font-variant-numeric: tabular-nums;' : ''].filter(Boolean).join(' ');
  lines.push(`.sk-type-${n} { font: var(${P}-type-${n}); letter-spacing: var(${P}-type-${n}-tracking);${extra ? ' ' + extra : ''} }`);
}
lines.push('.sk-num { font-variant-numeric: tabular-nums; }');
lines.push(`.sk-focusable:focus-visible { outline: var(${P}-focus-ring-width) solid var(${P}-color-focus-ring); outline-offset: var(${P}-focus-ring-offset); }`);
lines.push(`.sk-target { min-width: var(${P}-touch-min); min-height: var(${P}-touch-min); }`);
lines.push('/* Paper grain: static tile, decorative zones only (hero margins, empty-state plate). Never');
lines.push('   behind body text, verdicts, cards or sheets. Opacity is 0 in dark mode. */');
lines.push(`.sk-grain { position: relative; isolation: isolate; }`);
lines.push(`.sk-grain::before { content: ""; position: absolute; inset: 0; z-index: -1; pointer-events: none; background-image: var(${P}-grain-tile); background-size: 160px 160px; opacity: var(${P}-grain-opacity); }`);
writeFileSync(join(here, 'tokens.css'), lines.join('\n') + '\n');

