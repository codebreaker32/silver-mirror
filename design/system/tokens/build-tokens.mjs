const P = '--sk';
const lines = [];
const decl = (name, value, indent = '  ') => lines.push(`${indent}${P}-${name}: ${value};`);
const primName = (ref) => ref.slice(1, -1).replace(/\./g, '-');

function cssColorRef(ref, mode) {
  // Semantic colour value -> var(--sk-<primitive>) when it aliases a primitive.
  if (isAlias(ref)) {
    const hit = lookup(tokens, ref, mode);
    if (hit.kind === 'primitive') return `var(${P}-${primName(ref)})`;
  }
  return ref;
}

function cssRef(value, key) {
  // Component-layer value -> CSS value (var() reference or literal with unit).
  if (isAlias(value)) {
    const [head, ...rest] = value.slice(1, -1).split('.');
    const path = rest.join('-');
    switch (head) {
      case 'color': return `var(${P}-color-${kebab(path)})`;
      case 'verdict': return `var(${P}-verdict-${kebab(path)})`;
      case 'meter': return `var(${P}-meter-${kebab(path)})`;
      case 'space': return `var(${P}-space-${kebab(path)})`;
      case 'radius': return `var(${P}-radius-${path})`;
      case 'type': return `var(${P}-type-${kebab(path)})`;
      case 'elevation': return /^\d$/.test(path) ? `var(${P}-elevation-${path}-shadow)` : `var(${P}-elevation-${path})`;
      case 'icon': return `var(${P}-icon-${kebab(path)})`;
      case 'touch': return `var(${P}-touch-${kebab(path)})`;
      case 'z': return `var(${P}-z-${kebab(path)})`;
      case 'duration': return `var(${P}-duration-${kebab(path)})`;
      default: return `var(${P}-${primName(value)})`;
    }
  }
  if (typeof value === 'number') {
    if (/Pct$/.test(key)) return `${value}%`;
    if (/(aspect|opacity|items|segments|elevation|FontScale|columns)$/i.test(key)) return String(value);
    return `${value}px`;
  }
  if (typeof value === 'string' && /^(#|rgba?\(|transparent$|none$|dashed$|solid$|start$|horizontal$)/.test(value)) return value;
  return null; // prose, component references, icon names: not CSS values
}

function emitComponents(obj, prefix) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$') || Array.isArray(v) || typeof v === 'boolean') continue;
    const name = prefix ? `${prefix}-${kebab(k)}` : kebab(k);
    if (v && typeof v === 'object') { emitComponents(v, name); continue; }
    const css = cssRef(v, k);
    if (css !== null) decl(name, css);
    // Type aliases carry tracking / case / figures too, so a component var is complete on its own.
    if (isAlias(v) && v.startsWith('{type.')) {
      const st = tokens.typography.scale[v.slice(6, -1)];
      const n = kebab(v.slice(6, -1));
      decl(`${name}-tracking`, `var(${P}-type-${n}-tracking)`);
      if (st.transform) decl(`${name}-transform`, st.transform);
      if (st.numeric === 'tabular') decl(`${name}-numeric`, 'tabular-nums');
    }
  }
}

function emitSemantic(mode) {
  const sem = strip(tokens.semantic.color[mode]);
  for (const [k, v] of Object.entries(sem)) {
    if (k === 'verdict') {
      for (const [vk, vv] of Object.entries(v)) for (const [p, c] of Object.entries(vv)) decl(`verdict-${vk}-${p}`, cssColorRef(c, mode));
    } else if (k === 'meter') {
      for (const [p, c] of Object.entries(v)) decl(`meter-${p}`, cssColorRef(c, mode));
    } else if (typeof v === 'object') {
      for (const [p, c] of Object.entries(v)) decl(`color-${k}-${p}`, cssColorRef(c, mode));
    } else {
      decl(`color-${k}`, cssColorRef(v, mode));
    }
  }
  for (const [lvl, e] of Object.entries(strip(tokens.elevation[mode]))) {
    decl(`elevation-${lvl}-surface`, cssRef(e.surface));
    decl(`elevation-${lvl}-border`, e.border === 'none' ? 'transparent' : cssRef(e.border));
    decl(`elevation-${lvl}-shadow`, e.shadow);
  }
  decl('grain-opacity', String(tokens.texture.grain[mode].opacity));
}

